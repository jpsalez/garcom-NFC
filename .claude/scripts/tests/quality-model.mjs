import assert from 'node:assert/strict';
import { defaults, evaluate, validateReport } from '../static/js/ui/quality-model.js';
const snapshot='a'.repeat(64),fn={id:'back-end/src/a.ts:2:a',cc:14,length:68};
const get=id=>defaults.find(r=>r.id===id);
assert.equal(evaluate(get('coverage'),fn,null,snapshot).state,'Não medido');
const report={snapshot,testsPassed:true,functions:{[fn.id]:{coverage:82,mutation:72}}};
validateReport(report);
assert.equal(evaluate(get('tests'),fn,report,snapshot).state,'Dentro do critério');
assert.equal(evaluate(get('tests'),fn,{...report,testsPassed:false},snapshot).state,'Bloqueio');
assert.equal(evaluate(get('coverage'),fn,report,'b'.repeat(64)).state,'Não medido');
assert.equal(evaluate(get('crap'),fn,null,snapshot).state,'Não medido');
assert.ok(Math.abs(evaluate(get('crap'),fn,report,snapshot).value-15.143072)<.000001);
assert.equal(evaluate(get('cc'),fn,report,snapshot).state,'Atenção');
assert.equal(evaluate({...get('cc'),limit:20},fn,report,snapshot).state,'Dentro do critério');
assert.equal(evaluate(get('srp'),fn,report,snapshot).state,'Revisão humana');
assert.equal(evaluate(get('mutation'),fn,report,snapshot).state,'Desativada');
assert.throws(()=>validateReport({...report,testsPassed:'true'}));
assert.throws(()=>validateReport({...report,functions:{[fn.id]:{coverage:101}}}));
assert.throws(()=>validateReport({...report,functions:[]}));
console.log('PASS: quality model · resultados ausentes/antigos, limites, CRAP, revisão humana e importação.');
